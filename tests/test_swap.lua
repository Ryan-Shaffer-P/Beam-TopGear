-- Swap cars (0.9.36, Ryan: "everyone runs a course as buses"): an event gives everyone the same car. As each driver
-- reaches the start their own car is parked behind the start line and the event's car comes on the start grid (their
-- own game spawns it, like the reasonably priced car); at the end it goes and they're back in their own - untouched.
local t = require("t")
local World = require("world")
local F = require("fixtures")
local p = F.p

local function course(extra)
  local e = { name = "Bus Race", type = "race", timeLimit = 300, start = p(500), checkpoints = { p(700), p(900) }, via = {},
              swap = { model = "pickup", config = "d35_A" } }
  for k, v in pairs(extra or {}) do e[k] = v end
  return F.config({ e })
end
local function count(pl) local n = 0 for _ in pairs(pl.vehicles) do n = n + 1 end return n end

local function toStart(w, A, B)
  w:chat(A, "/tg start"); w:buy(A, "covet", "base_M"); w:buy(B, "pessima", "base_M")
  w:chat(A, "/tg ready"); w:chat(B, "/tg ready"); w:step(1)
  w:drive(A, p(500, 5), 40); w:drive(B, p(500, -5), 40); w:step(3)
end

t.test("swap cars: everyone gets the event car on the grid, their own parked behind; back in their own at the end", function()
  local w = World.new({ files = F.files(course()) })
  local A, B = w:join("Alice"), w:join("Bob")
  w:chat(A, "/tg start"); w:buy(A, "covet", "base_M"); w:buy(B, "pessima", "base_M")
  w:chat(A, "/tg ready"); w:chat(B, "/tg ready"); w:step(1)
  local ownA, ownB = A.current, B.current
  w:damage(A, 3000); w:step(2.5)   -- (Alice's own car is dented: it stays that way)
  w:drive(A, p(500, 5), 40); w:step(3)
  t.ok(w:chatHas(A, "Today everyone drives the same car: your event car (pickup / d35_A) is on the start line"))
  t.eq(A.current.model, "pickup", "Alice is in the event car")
  t.ok(ownA.pos.x < 470, "her own car's parked behind the start line: " .. ownA.pos.x)
  t.eq(count(A), 2)
  w:chat(A, "/tg go")
  t.ok(w:chatHas(A, "Can't start yet - still waiting for: Bob"), "Bob isn't there yet")
  w:drive(B, p(500, -5), 40); w:step(3)
  t.eq(B.current.model, "pickup")
  w:chat(A, "/tg go"); w:waitFor(function() return w:sawMessage(A, "GO!") end, 10, "GO")
  local busA = A.current
  w:driveAll({ { A, p(900), 40 }, { B, p(900), 30 } })
  w:damage(A, 3000)   -- (the bus got dented after the finish line: not Alice's own car)
  w:waitFor(function() return w:state(A).phase ~= "event" end, 15, "the results")
  w:step(2)
  t.ok(w:chatHas(A, "1st  Alice"), "Alice won in the bus")
  t.eq(A.current, ownA, "back in her own car"); t.eq(B.current, ownB)
  t.eq(count(A), 1, "the event car's gone")
  t.eq(ownA.damage, 3000, "her own car as she left it")
  t.ok(busA ~= ownA)
  w:assertClean()
end)

t.test("swap cars: a tow in the event car is free and no DSQ - a fresh one on the line, the course again", function()
  local w = World.new({ files = F.files(course()) })
  local A, B = w:join("Alice"), w:join("Bob")
  toStart(w, A, B)
  local cash = w:state(A).cash
  w:chat(A, "/tg go"); w:waitFor(function() return w:sawMessage(A, "GO!") end, 10, "GO")
  w:drive(A, p(700), 40); w:step(1)
  w:chat(A, "/tg tow"); w:step(3)
  t.ok(w:chatHas(B, "Alice needs a fresh event car (pickup / d35_A) - back to the start line; the clock keeps running."))
  t.ok(not w:chatHas(A, "disqualified"), "no DSQ")
  t.eq(w:state(A).cash, cash, "free")
  t.eq(A.current.model, "pickup"); t.ok(math.abs(A.current.pos.x - 500) < 25, "on the start line")
  t.eq(w:state(A).target.label, "Checkpoint 1/1", "the course again from checkpoint 1")
  w:driveAll({ { A, p(900), 40 }, { B, p(900), 30 } })
  w:waitFor(function() return w:state(A).phase ~= "event" end, 15, "the results")
  t.ok(w:chatHas(A, "Alice -"), "Alice finished")
  w:assertClean()
end)

t.test("swap cars, time trial: everyone in one on the grid; a finished driver's back in their own when the next goes", function()
  local w = World.new({ files = F.files(course({ solo = true })) })
  local A, B = w:join("Alice"), w:join("Bob")
  w:chat(A, "/tg start"); w:buy(A, "covet", "base_M"); w:buy(B, "pessima", "base_M")
  w:chat(A, "/tg ready"); w:chat(B, "/tg ready"); w:step(1)
  local ownA = A.current
  w:drive(A, p(500, 5), 40); w:drive(B, p(500, -5), 40); w:step(1)
  w:chat(A, "/tg go")
  w:waitFor(function() return w:sawMessage(A, "Alice: GO!") end, 15, "Alice's GO")
  t.eq(A.current.model, "pickup"); t.eq(B.current.model, "pickup", "Bob waits in his")
  w:drive(A, p(700), 40); w:drive(A, p(900), 40)
  w:waitFor(function() return w:sawMessage(B, "Bob: GO!") end, 15, "Bob's GO")
  t.eq(A.current, ownA, "Alice is back in her own car")
  w:drive(B, p(700), 40); w:drive(B, p(900), 40)
  w:waitFor(function() return w:state(A).phase ~= "event" end, 15, "the results")
  w:assertClean()
end)

t.test("swap cars: no event car (MaxCars 1) - that driver drives their own", function()
  local w = World.new({ files = F.files(course()) })
  local A, B = w:join("Alice"), w:join("Bob")
  A.client.sb.env.core_vehicles.spawnNewVehicle = function() return nil end   -- BeamMP refuses a 2nd car
  toStart(w, A, B)
  w:waitFor(function() return w:chatHas(A, "Your event car didn't appear") end, 30, "the timeout")
  t.eq(A.current.model, "covet", "in her own car")
  w:chat(A, "/tg go"); w:waitFor(function() return w:sawMessage(A, "GO!") end, 10, "GO")
  w:driveAll({ { A, p(900), 40 }, { B, p(900), 30 } })
  w:waitFor(function() return w:state(A).phase ~= "event" end, 15, "the results")
  t.ok(w:chatHas(A, "1st  Alice"), "no jumped start: her own car took her grid spot")
  w:dropWarning("couldn't spawn pickup")   -- (the expected warning: the game refused the 2nd car)
  w:assertClean()
end)

t.test("setswap: the car I'm in / a model / off; the Event options row; not for a trailer delivery", function()
  local cfg = course(); cfg.events[1].swap = nil   -- (no swap to start with)
  local w = World.new({ files = F.files(cfg) })
  local A = w:join("Alice")
  w:chat(A, "/tg menu"); w:clientSpawn(A, "miramar", {}); w:step(2)
  t.ok(A.client.im.textOf("Top Gear Challenge"):find("Cars: everyone drives their own", 1, true))
  A.client.im.click("Everyone drives the car I'm in##swapmine"); w:step(1)
  t.ok(w:chatHas(A, "everyone drives miramar"), "the car she's in")
  t.ok(A.client.im.textOf("Top Gear Challenge"):find("Cars: everyone drives miramar", 1, true))
  A.client.im.click("Their own cars##swapoff"); w:step(1)
  t.ok(w:chatHas(A, "everyone drives their own car"))
  w:chat(A, "/tg settype 1 trailer"); w:chat(A, "/tg setswap 1 pickup")
  t.ok(w:chatHas(A, "not for a Trailer delivery event"))
  w:assertClean()
end)
