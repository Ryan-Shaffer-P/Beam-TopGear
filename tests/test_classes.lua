end)

t.test("a class with no cars won't start; the admin tab builds a class with buttons", function()
  local w = World.new({ files = F.files(F.twoRaces()) })
  local A = w:join("Alice")
  setup(w, A)
  w:chat(A, "/tg class new empty")
  w:chat(A, "/tg class use empty")
  w:chat(A, "/tg start")
  t.ok(w:chatHas(A, "Today's class (empty) has no cars"))
  t.eq(w:state(A) and w:state(A).phase or "idle", "idle")

  w:chat(A, "/tg menu"); w:step(2.5)
  local im = A.client.im
  t.ok(im.hasButton("> Edit"), "class list with Edit buttons (the one being edited is marked)")
  im.setText("##newclass", "trucks"); im.click("New class (one word)##clsnew"); w:step(2.5)
  t.ok(w:chatHas(A, "Made class trucks."))
  im.click("Edit##clsedit_trucks"); w:step(2.5)
  t.match(im.textOf(WIN), "CLASS trucks")
  -- the field list starts on Country; pick "Type" (4th) and add "Truck"
  im.click("Type##fld_type"); w:step(0.5)
  im.setText("##clsvalue", "Truck"); im.click("Add rule##clsaddrule"); w:step(2.5)
  t.ok(w:chatHas(A, "trucks: Type: Truck - 2 trims, $6,800 to $12,500."))
  t.ok(im.hasButton("Set price"), "the class's cars, each with a price box")
  im.click("Use##clsuse_trucks"); w:step(1)
  t.ok(w:chatHas(A, "Next challenge's cars: trucks"))
  w:assertClean()
end)
