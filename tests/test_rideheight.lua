-- /tg rideheight scan (0.9.36, Ryan: how many cars have adjustable ride height?) - the admin's game reads every
-- catalogue model's parts (harness: sport coilovers on the adjustable cars set "$springheight_F"; a spoiler's
-- "height" doesn't count), each trim's .pc says what it comes with. Results -> rideheight.json.
local t = require("t")
local World = require("world")
local F = require("fixtures")
local json = require("json")

t.test("ride height scan: per model and trim, as they come or with a part; saved; list", function()
  local w = World.new({ files = F.files(F.twoRaces()) })
  local A = w:join("Alice")
  w:chat(A, "/tg rideheight")
  t.ok(w:chatHas(A, "No ride height scan yet - /tg rideheight scan"))
  w:chat(A, "/tg importprices"); w:step(3)   -- (the harness's own cars: covet, pessima, pickup, miramar, modcar)
  w:chat(A, "/tg menu"); w:step(1)
  A.client.im.click("Scan ride height##rhscan")
  w:step(1)
  t.ok(w:chatHas(A, "Scanning 5 models' parts in your game for ride height settings"))
  w:waitFor(function() return w:chatHas(A, "Ride height scan done") end, 20, "the scan")
  t.ok(w:chatHas(A, "Ride height: 1 of 5 models have it on at least one trim - 2 of 10 trims as they come."))
  t.ok(w:chatHas(A, "1 more model can get it with a part"), "the Pessima: the coilovers would add it")
  local saved = json.decode(assert(w.files["Resources/Server/TopGear/rideheight.json"], "rideheight.json written"))
  local covet = saved.models.covet
  t.eq(covet.trims.base_M, false); t.eq(covet.trims.sport_M, true); t.eq(covet.trims.gtz_M, true)
  t.eq(covet.vars[1].name, "$springheight_F"); t.eq(covet.vars[1].max, 0.08)
  t.eq(covet.other[1], "$spoiler_height", "a spoiler's height: noted, not counted")
  t.eq(saved.models.pickup.possible, nil, "the pickup: nothing")
  w:chat(A, "/tg rideheight list")
  t.ok(w:chatHas(A, "As they come (trims): Ibishu Covet (2)"))
  t.ok(w:chatHas(A, "With a part: Ibishu Pessima"))
  w:assertClean()
end)

t.test("ride height results survive a restart", function()
  local w = World.new({ files = F.files(F.twoRaces()) })
  local A = w:join("Alice")
  w:chat(A, "/tg importprices"); w:step(3)
  w:chat(A, "/tg rideheight scan")
  w:waitFor(function() return w:chatHas(A, "Ride height scan done") end, 20, "the scan")
  local w2 = World.new({ files = w.files })
  local B = w2:join("Alice")
  w2:chat(B, "/tg rideheight")
  t.ok(w2:chatHas(B, "Ride height: 1 of 5 models have it on at least one trim"))
  w2:assertClean()
end)
