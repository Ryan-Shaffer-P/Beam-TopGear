t.test("admin: Rerun a finished event - results taken back, the workshop after it cancelled, back to its start (0.9.35)", function()
  local cfg = readyGo(F.config({ race(), race({ name = "Drag Two", start = p(1500), checkpoints = { p(1900) } }) }))
  cfg.modes = { turbo = true }; cfg.workshopEvery = 1
  local w = World.new({ files = F.files(cfg) })
  local A, B = w:join("Alice"), w:join("Bob")
  w:chat(A, "/tg menu")
  toStart(w, A, B)
  local before = { A = w:state(A).cash, B = w:state(B).cash, ga = #(w:ui(A).me.glovebox or {}), gb = #(w:ui(B).me.glovebox or {}) }
  local function run()
    w:chat(A, "/tg ready"); w:chat(B, "/tg ready"); w:chat(A, "/tg go")
    w:waitFor(function() return w:sawMessage(A, "GO!") end, 10, "GO")
    w:driveAll({ { A, p(900), 40 }, { B, p(900), 30 } })
    w:waitFor(function() return w:state(A).phase == "workshop" end, 15, "the workshop")
    w:step(1)
  end
  run()
  t.ok(w:state(A).cash > before.A, "Alice won prize money")
  t.ok(#w:ui(B).me.glovebox > before.gb, "Bob won Turbo prizes (cleanest, last place)")
  t.ok(A.client.im.hasButton("Rerun Drag"), "the Challenge box button")
  A.client.im.click("Rerun Drag##rerunevent"); w:step(0.5); A.client.im.click("Really? Rerun Drag##rerunevent"); w:step(3)
  t.ok(w:chatHas(B, "Drag will be run again - its results are taken back (prize money, points, Turbo prizes)"))
  t.eq(w:state(A).phase, "travel")
  t.eq(w:state(A).cash, before.A, "Alice's prize money taken back")
  t.eq(w:state(B).cash, before.B, "Bob's too")
  t.eq(#(w:ui(B).me.glovebox or {}), before.gb, "the Turbo prizes those results gave")
  t.eq(#(w:ui(A).me.glovebox or {}), before.ga)
  for _, s in ipairs(w:ui(A).standings) do t.eq(s.points, 0, s.name .. "'s points"); t.eq(s.wins, 0, s.name .. "'s wins") end
  t.ok(math.abs(A.current.pos.x - 500) < 15 and math.abs(B.current.pos.x - 500) < 15, "both at Drag's start")
  t.ok(not A.client.im.hasButton("Rerun Drag"), "once")
  -- run it again: scored once, and the workshop opens again as workshop 1
  run()
  local wins = 0
  for _, s in ipairs(w:ui(A).standings) do wins = wins + s.wins end
  t.eq(wins, 1, "one win in all")
  t.ok(w:chatHas(A, "Workshop inspection"), "inspected again")
  w:chat(A, "/tg next"); w:step(1)   -- (the workshop closes: on the way to Drag Two)
  t.ok(A.client.im.hasButton("Rerun Drag"), "still possible on the way to the next event")
  w:drive(A, p(1500, 5), 40); w:drive(B, p(1500, -5), 40); w:step(2.5)
  w:chat(A, "/tg ready"); w:chat(B, "/tg ready"); w:chat(A, "/tg go")
  w:waitFor(function() return w:sawMessage(A, "GO!") end, 10, "GO")
  w:chat(A, "/tg rerunevent")
  t.ok(w:chatHas(A, "An event is running - Restart event runs it again."), "not once the next event has started")
  -- the cancelled workshop's inspection is gone: at the finale, 2 inspections (workshop 1 + the finale), not 3
  w:driveAll({ { A, p(1900), 40 }, { B, p(1900), 30 } })
  w:waitFor(function() return w:state(A).phase == "finale" end, 15, "the finale")
  w:drive(A, p(5000), 40)
  t.ok(w:chatHas(A, "Drivability (average of 2 inspections)"), "the rerun's workshop counted once")
  w:assertClean()
end)

t.test("event starts face a way: Set start here takes the way the admin's car points; drivers see an arrow", function()
  local w = World.new({ files = F.files(F.config({ race() })) })
  local A, B = w:join("Alice"), w:join("Bob")
  w:buy(A, "covet", "base_M")
  w:place(A, p(500, 0), math.pi / 2); w:step(1.5)   -- facing +y (the first checkpoint is +x: the arrow says otherwise)
  w:chat(A, "/tg setstart 1")
  t.ok(w:chatHas(A, "event 1 start set (500.0, 0.0, 0.0), facing the way your car points"))
  local sd = w:serverConfig().events[1].startDir
  t.ok(math.abs(sd.x) < 0.01 and math.abs(sd.y - 1) < 0.01, "stored")
  w:assertClean()
  w = World.new({ files = w.files })   -- (the saved course, in a fresh challenge)
  A, B = w:join("Alice"), w:join("Bob")
  w:chat(A, "/tg start"); buyAll(w, A, B)
  w:chat(A, "/tg ready"); w:chat(B, "/tg ready"); w:step(2.5)
  local face = w:state(A).target.face
  t.ok(face and math.abs(face.y - 1) < 0.01, "the leg's target carries the way to face")
  local heads = 0
  for _, cy in ipairs(A.client.cylinders) do
    if math.abs(cy.a.x - 500) < 0.01 and math.abs(cy.a.y - 5) < 0.01 and cy.b.y < cy.a.y and cy.r == 0.15 then heads = heads + 1 end
  end
  t.eq(heads, 2, "an arrowhead 5 m up +y from the start")
  w:assertClean()
end)

