-- Beta testing fixes (0.9.20): Not ready, workshop tows, watching again, back behind the start after a time trial
-- run, restarting an event, admin take/dock/free respawn, trailers at I'm ready.
local t = require("t")
local World = require("world")
local F = require("fixtures")
local p = F.p

local WIN = "Top Gear Challenge"
local function readyGo(cfg) cfg.defaults.readyToGo = true; return cfg end
local function race(extra)
  local e = { name = "Drag", type = "race", timeLimit = 120, start = p(500), checkpoints = { p(900) }, via = {} }
  for k, v in pairs(extra or {}) do e[k] = v end
  return e
end
local function buyAll(w, A, B)
  w:buy(A, "covet", "base_M"); w:buy(B, "pessima", "base_M")
end
local function toStart(w, A, B, at)
  w:chat(A, "/tg start"); buyAll(w, A, B)
  w:chat(A, "/tg ready"); w:chat(B, "/tg ready")
  w:drive(A, p(at or 500, 5), 40); w:drive(B, p(at or 500, -5), 40); w:step(2.5)   -- (arrival order: Alice, Bob)
end

t.test("Not ready: the dealership countdown stops; a race start and the workshop wait again", function()
  local cfg = readyGo(F.config({ race(), race({ name = "Drag Two", start = p(1500), checkpoints = { p(1900) } }) }))
  cfg.defaults.readyCountdown = 5; cfg.workshopEvery = 1
  local w = World.new({ files = F.files(cfg) })
  local A, B = w:join("Alice"), w:join("Bob")
  w:chat(A, "/tg start"); buyAll(w, A, B)
  w:chat(A, "/tg ready"); w:chat(B, "/tg ready")
  t.ok(w:chatHas(A, "Everyone's ready! The challenge starts in 5 seconds."))
  w:step(2.5)
  t.ok(A.client.im.hasButton("Not ready - undo"), "the button")
  A.client.im.click("Not ready - undo##unready"); w:step(4)
  t.ok(w:chatHas(A, "Alice isn't ready after all - the countdown is stopped."))
  t.eq(w:state(A).phase, "dealer", "still at the dealership")
  w:chat(A, "/tg ready"); w:step(6)
  t.eq(w:state(A).phase, "travel")
  -- the race start
  w:driveAll({ { A, p(500, 5), 40 }, { B, p(500, -5), 40 } }); w:step(2.5)
  w:chat(A, "/tg ready"); w:chat(B, "/tg ready"); w:chat(B, "/tg unready")
  t.ok(w:chatHas(A, "Bob isn't ready after all."))
  w:chat(A, "/tg go")
  t.ok(w:chatHas(A, "Waiting for Bob to press I'm ready."))
  w:chat(B, "/tg ready"); w:chat(A, "/tg go")
  w:waitFor(function() return w:state(A).phase == "event" end, 10, "GO")
  w:chat(A, "/tg unready")
  t.ok(w:chatHas(A, "Too late - it's already started."))
  w:driveAll({ { A, p(900), 40 }, { B, p(900), 30 } })
  w:waitFor(function() return w:state(A).phase == "workshop" end, 10, "the workshop")
  w:chat(A, "/tg ready"); w:chat(B, "/tg ready"); w:chat(A, "/tg unready")
  t.ok(w:chatHas(A, "Alice isn't done in the workshop after all."))
  w:chat(B, "/tg go")
  t.ok(w:chatHas(B, "Waiting for Alice to press I'm ready."))
  w:assertClean()
end)

