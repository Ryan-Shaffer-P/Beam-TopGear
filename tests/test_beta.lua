t.test("time trial: a finished driver's car goes behind the start after a 5 s countdown, then the next run", function()
  local cfg = F.config({ race({ solo = true }) })
  cfg.defaults.backToStartSeconds = 5
  local w = World.new({ files = F.files(cfg) })
  local A, B = w:join("Alice"), w:join("Bob")
  toStart(w, A, B); w:chat(A, "/tg go")
  w:waitFor(function() return w:sawMessage(A, "Alice: GO!") end, 10, "Alice's GO")
  w:drive(A, p(900), 40); w:step(1)
  t.ok(w:sawMessage(A, "Back to the start in"), "the countdown on her screen")
  t.ok(not w:sawMessage(B, "Bob: GO!") and not w:chatHas(B, "Bob is up"), "Bob waits")
  t.ok(A.current.pos.x > 850, "her car is still at the finish")
  w:step(5)
  t.ok(w:chatHas(A, "Your car's been moved behind the start line - as it is, no repairs."))
  t.ok(A.current.pos.x < 500 - 30, "behind the start line (the start at x = 500, the track runs +x)")
  t.ok(w:chatHas(B, "Bob is up"), "then Bob's turn")
  w:assertClean()
end)

