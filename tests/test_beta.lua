t.test("admin: Take cash, Dock points and a free respawn from the Players box", function()
  local w = World.new({ files = F.files(F.config({ race() })) })
  local A, B = w:join("Alice"), w:join("Bob")
  toStart(w, A, B)
  local cash = w:state(B).cash
  w:step(2.5)   -- (the window opened by itself when the challenge started)
  A.client.im.click("Bob##pl_Bob"); w:step(0.5)
  A.client.im.setInt("Cash##admcash", 700); A.client.im.setInt("Points##admpts", 2); w:step(0.5)
  A.client.im.click("Take##admtake"); w:step(0.5)
  t.ok(w:chatHas(B, "The producers take $700 from Bob."))
  t.eq(w:state(B).cash, cash - 700)
  A.client.im.click("Dock##admdock"); w:step(0.5)
  t.eq(w:state(B).points, -2)
  w:damage(B, 3000); w:step(2.5)
  A.client.im.click("Free respawn##admrespawn"); w:step(3)
  t.ok(w:chatHas(B, "The producers give Bob a free respawn."))
  t.eq(B.current.damage, 0, "repaired")
  t.eq(w:state(B).cash, cash - 700, "free")
  t.noLine(B.chat, "billed")
  w:assertClean()
end)

