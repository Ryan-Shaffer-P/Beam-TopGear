t.test("a tow in the workshop goes to the nearest workshop (a car stuck or beyond repair)", function()
  local cfg = F.config({ race(), race({ name = "Drag Two", start = p(1500), checkpoints = { p(1900) } }) })
  cfg.workshopEvery = 1
  cfg.workshopSpots = { { x = 950, y = 100, z = 0, name = "Gas station" }, { x = 5000, y = 0, z = 0, name = "Far" } }
  local w = World.new({ files = F.files(cfg) })
  local A, B = w:join("Alice"), w:join("Bob")
  toStart(w, A, B); w:chat(A, "/tg go")
  w:waitFor(function() return w:state(A).phase == "event" end, 10, "GO")
  w:driveAll({ { A, p(900), 40 }, { B, p(900), 30 } })
  w:waitFor(function() return w:state(A).phase == "workshop" end, 10, "the workshop")
  w:drive(A, p(1200, -300), 30)   -- stuck in a ditch on the way
  w:chat(A, "/tg tow"); w:step(3)
  t.ok(w:chatHas(A, "towed to the workshop at Gas station"))
  local pos = A.current.pos
  t.ok(math.abs(pos.x - 950) < 1 and math.abs(pos.y - 100) < 1, "at the gas station")
  t.eq(w:ui(A).me.inShop, true, "in the workshop")
  w:chat(B, "/tg tow"); w:step(3)
  t.ok(math.abs(B.current.pos.x - 950) > 3, "the next tow parks beside it, not on top")
  w:assertClean()
end)

